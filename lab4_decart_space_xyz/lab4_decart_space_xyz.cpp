#include <iostream>                                         // подключение директивы препроцессора
using namespace std;
int main()
{
    double x, y, z;
    cin >> x >> y >> z;

                                                            // все **2 чтобы не тратить ресурс процессора
    const double rad_sph_2 = 4.0;                           // 2 в квадрате
    const double rad_cyl_2 = 0.25;                          // 0.5 в квадрате
    double x_ = x - 3, y_ = y - 3, z_ = z - 3;              // тут находим вектор, это разница между началом и концом
    double dist_2 = x_ * x_ + y_ * y_ + z_ * z_;            //  считаем дистанцию от центра и проверяем зону 1, также это ГИПОТЕНУЗА для треугольника от центра
    double scl = x_ * 1 + y_ * 1 + z_ * 1;                  // насколько далеко точка продвинулась вдоль оси цил 
    double proekt = (scl * scl) / 3.0;                      // квадрат длины проекции, делим на 3 так как длина вектора 1,1,1 в квадрате (1+1+1)=3
    double rast = dist_2 - proekt;                          // Т.ПИФАГОРА квадрат расстояния до оси = квадрат гипотенузы (rdc2) - квадрат длины проекции (proekshn) КАТЕТ2
    if (dist_2 > rad_sph_2) {                               // квадр раст до центра и радиус шарика
        cout << "Zone 1\n";
    }
    else if (rast <= rad_cyl_2) {                           // квадр раст до оси и радуис цилиндра
        cout << "Zone 3\n";
    }
    else {
        cout << "Zone 2\n";                                 // в шарике но не в цилиндре
    }

    return 0;
}