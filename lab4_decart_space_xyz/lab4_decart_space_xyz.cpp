#include <iostream> // !!!111111!! подключение директивы препроцессора
using namespace std;
int main()
{
    double x, y, z;
    cin >> x >> y >> z;

    // все в квадрат чтоб считать проще было
    const double rshar2 = 4.0;      // 2**2
    const double rcil2 = 0.25;    // 0.5**2
    double x_ = x - 3, y_ = y - 3, z_ = z - 3;     // НАХОДИМ ВЕКТОР разница из конца начало вычитаем чтоб высчитать вектор от 333 до точки заданной
    double rdc2 = x_ * x_ + y_ * y_ + z_ * z_;    //  РАСЧЕТ РАСТОЯНИЯ ОТ ЦЕНТРА проверяем зону 1 сразу эт также гип1пп для оси цила
    double scalar = x_ * 1 + y_ * 1 + z_ * 1;                     // РАСЧЕТ СКАЛЯРА  *1 тк у цила 111 
    double proekshn = (scalar * scalar) / 3.0;      // НАКИДЫВАЕМ ПРОЕКЦИЮ деление на 3 тк увадр скаляр у цила 111 эт 3  (формула длины проекц на ось) КАТЕТ 1
    double rast = rdc2 - proekshn;  // Т.ПИФАГОРА квадрат расстояния до оси = квадрат гипотенузы (rdc2) - квадрат длины проекции (proekshn) КАТЕТ2
    if (rdc2 > rshar2) {         // квадр раст до центра и радиус шарика
        cout << "Zone 1\n";
    }
    else if (rast <= rcil2) {   // квадр раст до оси и радуис цилиндра
        cout << "Zone 3\n";
    }
    else {
        cout << "Zone 2\n"; // в шарике но не в цилиндре
    }

    return 0;
}