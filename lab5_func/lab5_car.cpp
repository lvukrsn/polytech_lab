float calculateSeries(float x) {
    float eps = 0.0001;
    float sum = 0;
    float term = 1;
    int n = 0;

    while (fabs(term) >= eps) {
        sum = term + sum;
        term *= x;
        n++;
    }

    // Возвращаем результат!
    return sum;
}

